#!/usr/bin/env python3
"""Writes THIRD-PARTY-LICENSES.md: the licenses of what slonbase ships inside its binary
(the dashboard's libraries and fonts, in full) and the Rust crates it is built from (name,
version, license and source of each). `--check` fails when the file is out of date, so CI
notices a changed dependency.

    scripts/third-party.py           write the file
    scripts/third-party.py --check   compare it with a fresh one
"""
import json
import pathlib
import subprocess
import sys

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "THIRD-PARTY-LICENSES.md"

BUNDLED = [
    ("Preact (the dashboard's UI library)", "ui/app/vendor/LICENSE-preact"),
    ("htm (the dashboard's template tags)", "ui/app/vendor/LICENSE-htm"),
    ("IBM Plex Sans (font)", "ui/app/fonts/LICENSE-ibm-plex-OFL.txt"),
    ("JetBrains Mono (font)", "ui/app/fonts/LICENSE-jetbrains-mono-OFL.txt"),
]


def build() -> str:
    lines = [
        "# Third-party licenses",
        "",
        "slonbase is licensed under the Apache License 2.0 (see `LICENSE` and `NOTICE`). The binary",
        "includes the software below, each under its own license. Generated by",
        "`scripts/third-party.py`; do not edit by hand.",
        "",
        "## Bundled in the dashboard",
        "",
    ]
    for title, path in BUNDLED:
        text = (root / path).read_text().strip()
        lines += [f"### {title}", "", "```text", text, "```", ""]
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=root, text=True
        )
    )
    crates = sorted(
        (p for p in meta["packages"] if p["source"]),
        key=lambda p: (p["name"], p["version"]),
    )
    lines += [
        "## Rust crates",
        "",
        f"{len(crates)} crates, each under the license shown (where a crate offers a choice, you",
        "may use it under any of the options). Each crate's source, with its license text, is at",
        "the address listed and in the crates.io package.",
        "",
        "| Crate | Version | License | Source |",
        "|---|---|---|---|",
    ]
    for p in crates:
        lic = (p.get("license") or "see source").replace("|", "/")
        repo = p.get("repository") or f"https://crates.io/crates/{p['name']}"
        lines.append(f"| {p['name']} | {p['version']} | {lic} | {repo} |")
    return "\n".join(lines) + "\n"


text = build()
if "--check" in sys.argv:
    if not out.exists() or out.read_text() != text:
        sys.exit("THIRD-PARTY-LICENSES.md is out of date: run scripts/third-party.py")
    print("THIRD-PARTY-LICENSES.md is up to date")
else:
    out.write_text(text)
    print(f"wrote {out.name}: {text.count(chr(10))} lines")
